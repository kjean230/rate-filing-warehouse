MANIFEST_DEFAULTS = {
    "manifest_schema_version": 1,
    "carrier_label_raw": "Test Carrier",
    "plan_year": 2027,
    "market": "individual",
    "source_item_key": "1",
    "etag": '"0x8DEE41154D40D80"',
    "last_modified": "Fri, 17 Jul 2026 14:40:22 GMT",
    "sharepoint_version": None,
    "prior_content_hash": None,
    "attempt_count": 1,
    "error": None,
}


def write_manifest_row(path: Path, **overrides) -> dict:
    row = {
        **MANIFEST_DEFAULTS,
        "run_id": "20260820T170641Z",
        "retrieved_at": "20260820T170645Z",
        "state": "OR",
        "filing_id": "or-2027-indv-test",
        "document_role": "urrt",
        "source_url": "https://example.invalid/urrt.xlsm",
        "http_status": 200,
        "content_type": "application/vnd.ms-excel.sheet.macroEnabled.12",
        "content_length": 1000,
        "content_hash": "sha256:" + "0" * 64,
        "unchanged": False,
        "stored_path": "OR/or-2027-indv-test/20260820T170641Z/urrt.xlsm",
    }
    row.update(overrides)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(row) + "\n")
    return row


