def truncated_pdf(tmp_path: Path) -> Path:
    """A PDF cut off mid-file. Used to prove a crash becomes a `failed` row."""
    good = make_pdf(tmp_path / "good.pdf", ["Hello world"])
    broken = tmp_path / "truncated.pdf"
    broken.write_bytes(good.read_bytes()[: len(good.read_bytes()) // 3])
    return broken


